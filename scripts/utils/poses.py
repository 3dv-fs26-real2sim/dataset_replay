"""6D pose trajectory loading for object replay.

Loads ``(N, 4, 4)`` homogeneous transformation matrices from ``.npz`` files,
typically representing an object's pose in camera frame across video frames
(generated by an external 6D pose estimator).

No Isaac Sim deps — safe to import before SimulationApp creation.
"""

from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation


def load_pose_trajectory(npz_path: Path) -> np.ndarray:
    """Load a stack of homogeneous transforms from a ``.npz`` file.

    The file must contain a single array of shape ``(N, 4, 4)``. Returned as
    ``float64`` so downstream maths is numerically stable.

    Raises:
        FileNotFoundError: if ``npz_path`` does not exist.
        ValueError: if the file does not contain a single ``(N, 4, 4)`` array.
    """
    npz_path = Path(npz_path)
    if not npz_path.exists():
        raise FileNotFoundError(f"Pose trajectory file not found: {npz_path}")

    with np.load(npz_path) as data:
        keys = list(data.keys())
        if len(keys) != 1:
            raise ValueError(
                f"Expected a single array in {npz_path}, found keys: {keys}"
            )
        arr = data[keys[0]]

    if arr.ndim != 3 or arr.shape[1:] != (4, 4):
        raise ValueError(
            f"Expected shape (N, 4, 4) in {npz_path}, got {arr.shape}"
        )
    return arr.astype(np.float64)


def transform_trajectory(
    T_target_from_source: np.ndarray, traj_source: np.ndarray
) -> np.ndarray:
    """Re-express a ``(N, 4, 4)`` trajectory in a different reference frame.

    Args:
        T_target_from_source: 4x4 transform mapping source-frame points to
            target-frame points.
        traj_source: ``(N, 4, 4)`` trajectory expressed in the source frame.

    Returns:
        ``(N, 4, 4)`` trajectory expressed in the target frame:
        ``T_target_from_source @ traj_source[i]`` for each frame ``i``.
    """
    if T_target_from_source.shape != (4, 4):
        raise ValueError(
            f"T_target_from_source must be 4x4, got {T_target_from_source.shape}"
        )
    if traj_source.ndim != 3 or traj_source.shape[1:] != (4, 4):
        raise ValueError(
            f"traj_source must have shape (N, 4, 4), got {traj_source.shape}"
        )
    return np.einsum("ij,njk->nik", T_target_from_source, traj_source)


def translation_matrix(t) -> np.ndarray:
    """Build a 4x4 homogeneous translation matrix from a 3-vector."""
    T = np.eye(4)
    T[:3, 3] = t
    return T


def average_poses(poses: list[np.ndarray]) -> np.ndarray:
    """Average multiple 4x4 poses (arithmetic mean of positions, rotation mean).

    Uses ``scipy.spatial.transform.Rotation.mean()`` for the rotation component.
    """
    positions = np.array([p[:3, 3] for p in poses])
    avg_pos = positions.mean(axis=0)
    rotations = Rotation.from_matrix([p[:3, :3] for p in poses])
    avg_rot = rotations.mean().as_matrix()
    result = np.eye(4)
    result[:3, :3] = avg_rot
    result[:3, 3] = avg_pos
    return result
